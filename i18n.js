  const listeners = [];
  const originals = new WeakMap(); // element → { html, attrs: { name: value } }
  let current = 'vi';

  function original(el) {
    let o = originals.get(el);
    if (!o) {
      o = { html: el.innerHTML, attrs: {} };
      originals.set(el, o);
    }
    return o;
  }

  function apply(lang) {
    const dict = PAGE[lang] || {};
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const o = original(el);
      const v = dict[el.dataset.i18n];
      el.innerHTML = lang !== 'vi' && v !== undefined ? v : o.html;
    });
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      const o = original(el);
      el.dataset.i18nAttr.split(';').forEach((pair) => {
        const [attr, key] = pair.split('=').map((s) => s.trim());
        if (!attr || !key) return;
        if (!(attr in o.attrs)) o.attrs[attr] = el.getAttribute(attr);
        const v = dict[key];
        el.setAttribute(attr, lang !== 'vi' && v !== undefined ? v : o.attrs[attr]);
      });
    });
  }

  function set(lang, { persist = true } = {}) {
    if (!LANGS.includes(lang)) lang = 'vi';
    current = lang;
    document.documentElement.lang = lang;
    apply(lang);
    document.querySelectorAll('#lang-switch [data-lang]').forEach((b) => {
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });
    if (persist) {
      try { localStorage.setItem(STORE_KEY, lang); } catch (_) { /* storage blocked */ }
    }
    listeners.forEach((fn) => fn(lang));
  }

  function initialLang() {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(fromUrl)) return fromUrl;
    try {
      const saved = localStorage.getItem(STORE_KEY);
      if (LANGS.includes(saved)) return saved;
    } catch (_) { /* storage blocked */ }
    return 'vi';
  }

  document.querySelectorAll('#lang-switch [data-lang]').forEach((b) => {
    b.addEventListener('click', () => { if (b.dataset.lang !== current) set(b.dataset.lang); });
  });

  set(initialLang(), { persist: false });

